"""Hand-drawn 12x14 mascots, all on the orange pencil mascot's body.

One body template, three skins (colors plus a head accessory), five faces.
Writes hooks/sprites.ts with every color on an xterm-256 cell (see quant.py),
and build/family.png, the sprites as Terminal.app shows them.

    python3 tools/make_sprites.py
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__)) + '/'
sys.path.insert(0, HERE)
from quant import snap  # noqa: E402

# o outline, b body, s shade (the side in shadow), l leg shade; '.' is clear.
# Row 0 and the top of row 1 are left to the accessory.
# Each column's run of color starts on an even row and ends on an odd one, so
# every terminal cell inside the body holds two pixels and is painted with its
# background, which also fills the gap Terminal.app leaves between rows. Rows 0
# and 1 hold the accessory; the body and legs take rows 2 to 13.
BODY = [
    '............',
    '............',
    '..oooooooo..',
    '..osbbbbbo..',
    '.osbbbbbbbo.',
    '.osbbbbbbbo.',
    'oosbbbbbbboo',
    'ossbbbbbbbso',
    'ossbbbbbbbso',
    'oosbbbbbbboo',
    '.osssbbbbbo.',
    '.oooooooooo.',
    '...ll..ll...',
    '...oo..oo...',
]

# Each accessory paints over the body: a key is the pixel, '.' leaves it.
ACCESSORY = {
    'pencil': [
        '.........kq.',
        '.........k..',
    ],
    'sprout': [
        '...gg..gg...',
        '....gGGg....',
    ],
    'crown': [
        '..y..yy..y..',
        '..yyyrryyy..',
    ],
}

COLORS = {
    'pencil': {'b': '#d7875f', 's': '#af5f5f', 'l': '#875f5f'},
    'sprout': {'b': '#5fd7d7', 's': '#5fafaf', 'l': '#5f8787'},
    'crown': {'b': '#af5fd7', 's': '#875fd7', 'l': '#5f5faf'},
}
SHARED = {
    'o': '#000000',
    'k': '#d7af87',  # pencil wood
    'q': '#5f3f3f',  # pencil lead
    'p': '#af8757',  # pencil wood, shaded
    'g': '#5faf5f',  # leaves
    'G': '#5f875f',  # stem
    'y': '#ffd700',  # crown gold
    'r': '#d70000',  # crown jewel
    'w': '#87d7ff',  # sweat drop
}

# The two eyes' columns and their rows, then each face as (row, col) offsets.
EYES = (4, 8)
EYE_ROW = 4
# Faces keep to pixel rows 4 and 5, one row of terminal cells, so no eye pixel
# is cut by the gap Terminal.app leaves between cell rows.
FACES = {
    'idle': [(0, 0), (1, 0)],
    'think': [(1, 0)],                     # a blink
    'work': [(0, -1), (1, -1)],            # looking aside
    'happy': [(0, 0), (1, -1), (1, 1)],    # ^ ^
    'dead': [(1, -1), (1, 0), (1, 1)],     # - - with a sweat drop
}
STATES = ['idle', 'think', 'work', 'happy', 'dead']


def draw(skin, face):
    grid = [list(row) for row in BODY]
    for y, row in enumerate(ACCESSORY[skin]):
        for x, ch in enumerate(row):
            if ch != '.':
                grid[y][x] = ch
    for col in EYES:
        for dy, dx in FACES[face]:
            grid[EYE_ROW + dy][col + dx] = 'o'
    if face == 'dead':
        grid[3][8] = 'w'
    palette = {**SHARED, **COLORS[skin]}
    return [[None if ch == '.' else palette[ch] for ch in row] for row in grid]


KEYS = '123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'


def main():
    out = [
        '// Generated by tools/make_sprites.py: 12x14 mascots on one shared body.',
        "// '.' is transparent; every other character indexes `palette` through",
        '// PALETTE_KEYS. Colors sit on xterm-256 cells, so Terminal.app (no 24-bit',
        '// color) shows the same sprite a truecolor terminal does.',
        "export type Skin = 'pencil' | 'sprout' | 'crown'",
        "export type Face = 'idle' | 'think' | 'work' | 'happy' | 'dead'",
        f"export const PALETTE_KEYS = '{KEYS}'",
        'export type Sprite = { palette: string[]; frames: Record<Face, string[]> }',
        '',
        'export const SPRITES: Record<Skin, Sprite> = {',
    ]
    sheet = Image.new('RGB', (14 * 5, 16 * 3), (38, 38, 38))
    for j, skin in enumerate(['pencil', 'sprout', 'crown']):
        pal, frames = [], {}
        for i, face in enumerate(STATES):
            rows = []
            for y, row in enumerate(draw(skin, face)):
                line = ''
                for x, color in enumerate(row):
                    if color is None:
                        line += '.'
                        continue
                    emit, shown = snap(color)
                    sheet.putpixel((i * 14 + 1 + x, j * 16 + 1 + y), tuple(int(shown[k:k + 2], 16) for k in (1, 3, 5)))
                    if emit not in pal:
                        pal.append(emit)
                    line += KEYS[pal.index(emit)]
                rows.append(line)
            frames[face] = rows
        out.append(f'  {skin}: {{')
        out.append('    palette: [' + ', '.join(f"'{p}'" for p in pal) + '],')
        out.append('    frames: {')
        for face in STATES:
            out.append(f'      {face}: [')
            out += [f"        '{r}'," for r in frames[face]]
            out.append('      ],')
        out.append('    },')
        out.append('  },')
    out.append('}')
    open(HERE + '../hooks/sprites.ts', 'w').write('\n'.join(out) + '\n')
    os.makedirs(HERE + 'build', exist_ok=True)
    sheet.resize((sheet.width * 14, sheet.height * 14), Image.NEAREST).save(HERE + 'build/family.png')


if __name__ == '__main__':
    main()
